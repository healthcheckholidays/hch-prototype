// ─── Helpers ──────────────────────────────────────────────────────────────────

export const getAddon = (id) => ADDON_TESTS.find(t => t.id === id) || null

export const getHospital = (id) => hospitals.find(h => h.id === id) || null

// Given selected addon IDs, score every hospital as full / partial / none.
export const matchHospitals = (selectedIds) => {
  if (selectedIds.length === 0) {
    return hospitals.map(h => ({ ...h, status: 'full', matched: 0, total: 0, missing: [] }))
  }
  return hospitals.map(h => {
    const missing = selectedIds.filter(id => {
      const t = getAddon(id)
      return t && !t.hosps.includes(h.id)
    })
    const matched = selectedIds.length - missing.length
    const status = missing.length === 0 ? 'full' : matched > 0 ? 'partial' : 'none'
    return {
      ...h,
      status,
      matched,
      total: selectedIds.length,
      missing: missing.map(id => getAddon(id)?.name ?? id),
    }
  })
}
